async function getJson(url) {
  const response = await fetch(url, { headers: { 'user-agent': 'anonlink-vocabulary-generator' } });
  if (!response.ok) return null;
  return response.json();
}

function capitalize(value) {
  const text = value.trim();
  if (text.length === 0) return text;
  const [first, ...rest] = text;
  return first.toLocaleUpperCase() + rest.join('');
}

function quote(value) {
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/** Native common name: the country's own language first, then any other. */
function nativeCountryName(country) {
  const native = country.name.native ?? {};
  const officialLanguageCodes = Object.keys(country.languages ?? {});

  for (const code of Object.keys(native)) {
    const matchesOfficial = officialLanguageCodes.some(
      (iso3) => iso3 === code || iso3.startsWith(code) || code.startsWith(iso3),
    );
    if (matchesOfficial && native[code]?.common) return native[code].common;
  }

  const first = Object.values(native).find((entry) => entry?.common);
  return first?.common ?? country.name.common;
}

async function generateCountries() {
  const countries = await getJson(COUNTRY_SOURCE);
  if (!Array.isArray(countries)) throw new Error('country source unavailable');

  const rows = countries
    .filter((country) => country.unMember === true && typeof country.cca2 === 'string')
    .map((country) => ({
      code: country.cca2,
      native: capitalize(nativeCountryName(country)),
      en: country.name.common,
      ru: country.translations?.rus?.common ?? country.name.common,
      zh: country.translations?.zho?.common ?? country.name.common,
    }))
    .sort((a, b) => a.en.localeCompare(b.en, 'en'));

  const body = rows
    .map(
      (row) =>
        `  { code: ${quote(row.code)}, native: ${quote(row.native)}, en: ${quote(row.en)}, ru: ${quote(row.ru)}, zh: ${quote(row.zh)} },`,
    )
    .join('\n');

  const file = `/**
 * Country vocabulary — generated data, do not edit by hand.
 *
 * Generated by \`scripts/generate-vocabularies.mjs\` from
 * https://github.com/mledoze/countries (snapshot ${SNAPSHOT}, UN members only).
 *
 * This is a **closed vocabulary** (docs/DECISIONS.md D30): the country code, not the
 * typed name, is what the profile stores and the filter compares. \`native\` is the one
 * name the interface shows, in the country's own language. \`en\`/\`ru\`/\`zh\` are search
 * aids for a picker, never displayed.
 *
 * The hand-written helpers (validation, lookup) live in \`countries.ts\`, so regenerating
 * this file cannot remove them.
 */
export interface CountryHint {
  /** ISO 3166-1 alpha-2. Stable, and the only field that is a code rather than a name. */
  readonly code: string;
  /** What the interface shows: the country's name in its own language. */
  readonly native: string;
  /** Search aids only. */
  readonly en: string;
  readonly ru: string;
  readonly zh: string;
}

export const COUNTRY_HINTS: readonly CountryHint[] = [
${body}
];
`;

  await writeFile('packages/shared/src/country-data.ts', file, 'utf8');
  return rows.length;
}

async function generateLanguages() {
  const [en, ru, zh] = await Promise.all([
    getJson(`${CLDR}/en/languages.json`),
    getJson(`${CLDR}/ru/languages.json`),
    getJson(`${CLDR}/zh/languages.json`),
  ]);
  if (!en || !ru || !zh) throw new Error('CLDR language source unavailable');

  const names = (raw, locale) => raw.main[locale].localeDisplayNames.languages;
  const enNames = names(en, 'en');
  const ruNames = names(ru, 'ru');
  const zhNames = names(zh, 'zh');

  const missing = [];
  const rows = [];

  for (const code of LANGUAGE_CODES) {
    const self = await getJson(`${CLDR}/${code}/languages.json`);
    const native = self ? names(self, code)[code] : null;
    if (!native) missing.push(code);

    rows.push({
      code,
      native: capitalize(native ?? enNames[code] ?? code),
      en: enNames[code] ?? code,
      ru: ruNames[code] ?? enNames[code] ?? code,
      zh: zhNames[code] ?? enNames[code] ?? code,
    });
  }

  const body = rows
    .map(
      (row) =>
        `  ${row.code}: { native: ${quote(row.native)}, en: ${quote(row.en)}, ru: ${quote(row.ru)}, zh: ${quote(row.zh)} },`,
    )
    .join('\n');

  const codes = rows.map((row) => quote(row.code)).join(', ');

  const file = `/**
 * The languages a person may declare, and the languages they may search for.
 *
 * Generated by \`scripts/generate-vocabularies.mjs\` from CLDR JSON (snapshot
 * ${SNAPSHOT}). The **code** is the domain value: it is what the API validates, what the
 * database stores and what matching compares. The names are presentation data, and
 * \`native\` is the one the owner asked for — every language named in itself («Русский»,
 * "English", «中文»), with \`en\`/\`ru\`/\`zh\` used only to search the picker.
 *
 * The list is deliberately a curated set (the most spoken languages plus those a
 * Russian-first audience is most likely to meet), not every ISO 639-1 code. Adding a code
 * is additive: no stored value becomes invalid.
 */
export const LANGUAGES = [${codes}] as const;

export type Language = (typeof LANGUAGES)[number];

export interface LanguageNames {
  /** The language's name in itself — what the interface shows. */
  readonly native: string;
  /** Search aids only. */
  readonly en: string;
  readonly ru: string;
  readonly zh: string;
}

export const LANGUAGE_NAMES: Record<Language, LanguageNames> = {
${body}
};
`;

  await writeFile('packages/shared/src/languages.ts', file, 'utf8');
  return { count: rows.length, missing };
}

const countries = await generateCountries();
const languages = await generateLanguages();

console.log(`countries: ${countries}`);
console.log(`languages: ${languages.count}`);
