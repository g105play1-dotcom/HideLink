/**
 * Regenerates the two closed vocabularies the interface offers as hints.
 *
 * Both lists are *data*, not policy: they are closed vocabularies that the server
 * validates against (a language in `languages.ts`, a country code in `countries.ts`), and
 * adding or removing an entry can never break a matching rule. They exist so the pickers
 * start with a complete, correctly spelled set instead of whatever a developer remembered.
 *
 * Sources (fetched, never invented):
 *  - countries: https://github.com/mledoze/countries — ISO 3166-1 records with the native
 *    common name per official language plus `rus`/`zho`/`eng` translations;
 *  - languages: CLDR JSON (unicode-org/cldr-json) — each language's own name from its own
 *    locale file, and the Russian/English/Chinese names from `ru`, `en`, `zh`.
 *
 * Run: `node scripts/generate-vocabularies.mjs`
 *
 * The output is committed, because the build must not depend on the network and the
 * repositories are not versioned against this project. Re-run deliberately, review the
 * diff, and update the snapshot date below.
 */
